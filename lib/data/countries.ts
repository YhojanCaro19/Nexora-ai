// lib/data/countries.ts
//
// Catálogo estático de países con su código ISO-3166-1 alpha-2, su código
// de marcación telefónica, y su zona horaria IANA principal. Se usa para
// el selector de país en cualquier campo de teléfono (PhoneField), para
// derivar la bandera sin depender de una librería ni de imágenes (ver
// lib/utils/phone.ts), y para que Reportes sepa cuándo es medianoche en
// cada negocio (ver lib/utils/timezone.ts).
//
// Por qué código de país es obligatorio en el teléfono: los reportes
// diarios se envían a la medianoche LOCAL del negocio, y la única forma
// confiable de saber en qué zona horaria está un negocio sin pedirle un
// dato aparte es a partir del código de país de su teléfono.
//
// Nota sobre `timezone`: para países con más de una zona horaria (EE.UU.,
// Canadá, Rusia, Brasil, México, Indonesia, Australia...) se eligió la
// zona de la ciudad más poblada/capital como aproximación razonable — no
// es exacto para todo el territorio de esos países, es un punto de partida
// documentado, no un hecho asumido en silencio.

